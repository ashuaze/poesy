const T2S_DICT: Record<string, string> = Object.entries(S2T_DICT).reduce(
  (acc, [s, t]) => {
    acc[t] = s;
    return acc;
  },
  {} as Record<string, string>
);

export function convertText(text: string, lang: 'chs' | 'cht'): string {
  if (!text) return '';
  if (lang === 'chs') {
    return text
      .split('')
      .map((ch) => T2S_DICT[ch] || ch)
      .join('');
  } else {
    return text
      .split('')
      .map((ch) => S2T_DICT[ch] || ch)
      .join('');
  }
}
